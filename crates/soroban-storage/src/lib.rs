/// Declares typed storage keys.
///
/// ```
/// use soroban_sdk::Address;
/// use soroban_storage::{days, storage_keys, TtlPolicy};
///
/// const TTL: TtlPolicy = TtlPolicy::new(days(30), days(60));
///
/// storage_keys! {
///     /// Contract administrator.
///     pub instance(TTL) Admin => Address;
///     pub persistent(TTL) Balance(owner: Address) => i128;
///     temporary(TtlPolicy::new(100, 200)) Lock(id: u64) => bool;
/// }
/// ```
///
/// Each entry has the form `[vis] kind(policy) Name(field: Type, ...) => Value;`:
///
/// * `kind` is `persistent`, `temporary` or `instance`;
/// * `policy` is a constant [`TtlPolicy`] expression, checked at compile
///   time;
/// * fields are optional (`Admin => Address` declares a singleton key), up to
///   12 per key.
///
/// Every entry becomes a struct (`Admin`, `Balance(pub Address)`, ...)
/// implementing [`TypedKey`], usable with the crate's functions or the
/// [`KeyExt`] methods. The structs derive `Clone`, `Debug`, `Eq` and
/// `PartialEq`; attributes and doc comments on an entry are applied to its
/// struct.
///
/// ## On-chain layout
///
/// Keys are encoded exactly like the variants of a `#[contracttype]` enum:
/// `Balance(owner)` is stored under the same ledger key as
/// `DataKey::Balance(owner)` would be (a vector of the variant name as a
/// `Symbol` followed by the fields). Contracts can therefore migrate from a
/// hand-written `DataKey` enum without moving any data, as long as the
/// struct names match the old variant names.
///
/// The calling crate must depend on `soroban-sdk` directly.
#[macro_export]
macro_rules! storage_keys {
    (
        $(
            $(#[$key_meta:meta])*
            $vis:vis $kind:ident ( $ttl:expr )
            $Key:ident $( ( $( $field:ident : $fty:ty ),* $(,)? ) )?
            => $Value:ty
        );* $(;)?
    ) => {
        $(
            $(#[$key_meta])*
            #[derive(Clone, Debug, Eq, PartialEq)]
            $vis struct $Key $( ( $( pub $fty ),* ) )?;

            // Reject invalid policies at compile time.
            const _: $crate::TtlPolicy = $crate::TtlPolicy::validated($ttl);

            impl $crate::TypedKey for $Key {
                type Value = $Value;
                type Kind = $crate::__storage_kind!($kind);
                const TTL: $crate::TtlPolicy = $ttl;

                fn to_key_val(&self, env: &::soroban_sdk::Env) -> ::soroban_sdk::Val {
                    let $Key $( ( $( ref $field ),* ) )? = *self;
                    ::soroban_sdk::IntoVal::into_val(
                        &(
                            ::soroban_sdk::Symbol::new(env, ::core::stringify!($Key)),
                            $( $( ::core::clone::Clone::clone($field), )* )?
                        ),
                        env,
                    )
                }
            }
        )*
    };
}

#[doc(hidden)]
#[macro_export]
macro_rules! __storage_kind {
    (persistent) => {
        $crate::Persistent
    };
    (temporary) => {
        $crate::Temporary
    };
    (instance) => {
        $crate::Instance
    };
    ($other:ident) => {
        ::core::compile_error!(::core::concat!(
            "unknown storage kind `",
            ::core::stringify!($other),
            "`: expected `persistent`, `temporary` or `instance`"
        ))
    };
}
