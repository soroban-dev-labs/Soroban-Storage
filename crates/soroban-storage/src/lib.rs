/// Method-call syntax for every [`TypedKey`]: `Balance(addr).get(&env)`.
///
/// Each method forwards to the free function of the same name.
pub trait KeyExt: TypedKey {
    /// See [`get`].
    fn get(&self, env: &Env) -> Option<Self::Value> {
        get(env, self)
    }
    /// See [`try_get`].
    fn try_get(&self, env: &Env) -> Result<Self::Value, StorageError> {
        try_get(env, self)
    }
    /// See [`require`].
    fn require(&self, env: &Env) -> Self::Value {
        require(env, self)
    }
    /// See [`require_or`].
    fn require_or<E>(&self, env: &Env, err: E) -> Self::Value
    where
        E: Into<Error> + soroban_sdk::SpecShakingMarker,
    {
        require_or(env, self, err)
    }
    /// See [`get_or`].
    fn get_or(&self, env: &Env, default: Self::Value) -> Self::Value {
        get_or(env, self, default)
    }
    /// See [`get_or_else`].
    fn get_or_else(&self, env: &Env, f: impl FnOnce() -> Self::Value) -> Self::Value {
        get_or_else(env, self, f)
    }
    /// See [`has`].
    fn has(&self, env: &Env) -> bool {
        has(env, self)
    }
    /// See [`set`].
    fn set(&self, env: &Env, val: &Self::Value) {
        set(env, self, val)
    }
    /// See [`update`].
    fn update(&self, env: &Env, f: impl FnOnce(Option<Self::Value>) -> Self::Value) -> Self::Value {
        update(env, self, f)
    }
    /// See [`try_update`].
    fn try_update<E>(
        &self,
        env: &Env,
        f: impl FnOnce(Option<Self::Value>) -> Result<Self::Value, E>,
    ) -> Result<Self::Value, E> {
        try_update(env, self, f)
    }
    /// See [`remove`].
    fn remove(&self, env: &Env) {
        remove(env, self)
    }
    /// See [`take`].
    fn take(&self, env: &Env) -> Option<Self::Value> {
        take(env, self)
    }
    /// See [`extend`].
    fn extend(&self, env: &Env) -> bool {
        extend(env, self)
    }
    /// See [`ttl`].
    #[cfg(any(test, feature = "testutils"))]
    fn ttl(&self, env: &Env) -> u32 {
        ttl(env, self)
    }
}

impl<K: TypedKey + ?Sized> KeyExt for K {}

