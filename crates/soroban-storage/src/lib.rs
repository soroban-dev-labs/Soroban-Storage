//! # soroban-storage
//!
//! Typed storage for Soroban contracts with explicit lifecycles and automatic
//! TTL management.
//!
//! Every key declares, once, where it lives and how long it should live:
//!
//! * its **storage kind** — [`Persistent`], [`Temporary`] or [`Instance`],
//! * its **value type** — reading or writing the wrong type won't compile,
//! * its **TTL policy** — a [`TtlPolicy`] applied on every access, so entries
//!   are extended before they can be archived or deleted.
//!
//! ```
//! use soroban_sdk::{Address, Env};
//! use soroban_storage::{days, storage_keys, TtlPolicy, KeyExt};
//!
//! const INSTANCE_TTL: TtlPolicy = TtlPolicy::new(days(7), days(30));
//! const BALANCE_TTL: TtlPolicy = TtlPolicy::new(days(30), days(90));
//! const NONCE_TTL: TtlPolicy = TtlPolicy::new(days(1), days(2));
//!
//! storage_keys! {
//!     /// Contract administrator.
//!     pub instance(INSTANCE_TTL) Admin => Address;
//!     /// Token balance per holder.
//!     pub persistent(BALANCE_TTL) Balance(owner: Address) => i128;
//!     /// Replay-protection nonces; fine to lose once expired.
//!     pub temporary(NONCE_TTL) Nonce(owner: Address, nonce: u64) => ();
//! }
//!
//! fn deposit(env: &Env, owner: Address, amount: i128) -> i128 {
//!     // Reads and writes extend the entry's TTL according to BALANCE_TTL.
//!     Balance(owner).update(env, |old| old.unwrap_or(0) + amount)
//! }
//! ```
//!
//! ## Expired and archived entries
//!
//! * **Temporary** entries are deleted when their TTL runs out; they then
//!   read as missing ([`get`] returns `None`).
//! * **Persistent** and **instance** entries are archived, not deleted. A
//!   transaction that touches an archived entry must restore it first; since
//!   protocol 23 this happens automatically when the entry is in the
//!   transaction footprint. Contract code therefore never observes an
//!   archived entry directly: it either sees the restored value or the
//!   transaction fails before execution.
//!
//! [`require`] fails the contract with [`StorageError::NotFound`] (a
//! contract error, code 1100) instead of a generic `unwrap` panic;
//! [`require_or`] fails with an error of your choosing, and [`try_get`]
//! returns a `Result`.
