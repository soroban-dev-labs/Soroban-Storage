/// A storage key that knows its value type, storage kind and TTL policy.
///
/// Usually generated by [`storage_keys!`], but can be implemented by hand:
///
/// ```
/// use soroban_sdk::{symbol_short, Env, IntoVal, Val};
/// use soroban_storage::{days, Persistent, TtlPolicy, TypedKey};
///
/// struct Counter;
///
/// impl TypedKey for Counter {
///     type Value = u64;
///     type Kind = Persistent;
///     const TTL: TtlPolicy = TtlPolicy::new(days(30), days(60));
///
///     fn to_key_val(&self, env: &Env) -> Val {
///         symbol_short!("COUNTER").into_val(env)
///     }
/// }
/// ```
pub trait TypedKey {
    /// Type of the value stored under this key.
    type Value: Storable;
    /// Where the entry lives.
    type Kind: StorageKind;
    /// How the entry's TTL is maintained.
    const TTL: TtlPolicy;

    /// The raw key written to the ledger.
    fn to_key_val(&self, env: &Env) -> Val;

    /// The storage lifecycle of this key, available at runtime.
    fn lifecycle(&self) -> Lifecycle {
        <Self::Kind as StorageKind>::LIFECYCLE
    }
}

/// A value that can be stored in contract storage.
///
/// Implemented for every type that converts to and from [`Val`], including
/// all `#[contracttype]` types.
pub trait Storable: IntoVal<Env, Val> + TryFromVal<Env, Val> {
    /// Converts a stored [`Val`] back into `Self`, failing the contract with
    /// [`StorageError::WrongType`] if the stored value has another type.
    fn from_stored(env: &Env, val: Val) -> Self;
}

impl<T: IntoVal<Env, Val> + TryFromVal<Env, Val>> Storable for T {
    fn from_stored(env: &Env, val: Val) -> Self {
        match T::try_from_val(env, &val) {
            Ok(v) => v,
            Err(_) => panic_with_error!(env, StorageError::WrongType),
        }
    }
}

